"""
Сборка курсовой работы в формате .docx (русский академический стиль).

Использование:
    python scripts/build_coursework.py

Создаёт: docs/coursework/курсовая_работа.docx

Форматирование:
  - Times New Roman 14pt
  - Полуторный межстрочный интервал
  - Поля: левое 30мм, правое 15мм, верх/низ 20мм
  - Отступ красной строки 1.25 см
  - А4
"""
from __future__ import annotations

from pathlib import Path

from docx import Document
from docx.enum.style import WD_STYLE_TYPE
from docx.enum.table import WD_ALIGN_VERTICAL, WD_TABLE_ALIGNMENT
